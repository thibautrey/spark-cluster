"""Export Pydantic response contracts as strict TypeScript types (no runtime dependency)."""
import json
import tempfile
from pathlib import Path
from spark_cluster.app import create_app
from spark_cluster.config import Settings
from spark_cluster.cluster_registry import ClusterTarget
from spark_cluster.setup_models import SetupJob, HardwareTopology, SetupCheck
from spark_cluster.runtime_library import RuntimeHost


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(x) for x in schema['enum'])
    for key, op in [('anyOf', ' | '), ('allOf', ' & ')]:
        if key in schema:
            return '(' + op.join(ts(x) for x in schema[key]) + ')'
    kind = schema.get('type')
    if kind == 'array':
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == 'object' or 'properties' in schema:
        if not schema.get('properties'):
            extra = schema.get('additionalProperties')
            return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
        return '{ ' + '; '.join(json.dumps(k) + ': ' + ts(v) for k, v in schema['properties'].items()) + ' }'
    return {'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'string': 'string', 'null': 'null'}.get(kind, 'unknown')


with tempfile.TemporaryDirectory(prefix='spark-ui-schema-') as folder:
    app = create_app(Settings(mode='demo', database_path=Path(folder) / 'schema.db', setup_state_path=Path(folder) / 'setup'))
    schemas = app.openapi()['components']['schemas']
    for model in (ClusterTarget, SetupJob, HardwareTopology, SetupCheck, RuntimeHost):
        schema = model.model_json_schema(ref_template='#/components/schemas/{model}')
        schemas.update(schema.pop('$defs', {}))
        schemas[model.__name__] = schema
    target = Path(__file__).resolve().parents[1] / 'frontend/src/lib/schema.ts'
    target.write_text('// Generated by scripts/export-ui-schema.py. Response defaults are always serialized.\n' + '\n'.join('export type ' + k + ' = ' + ts(v) + ';' for k, v in schemas.items()) + '\n')
    print(f'Exported {len(schemas)} API response contracts')
